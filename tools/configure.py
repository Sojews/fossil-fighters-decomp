#!/usr/bin/env python3
"""Generates build.ninja.  Usage: python3 tools/configure.py [usa]

Structure adapted from the Phantom Hourglass decomp's configure.py (zeldaret/ph, CC0).
"""
import argparse
import json
import platform
import subprocess
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description="Generates build.ninja")
parser.add_argument("version", nargs="?", default="usa", help="Game version")
parser.add_argument("-w", "--wine", help="Path to wibo/wine (default: tools/bin/wibo)")
args = parser.parse_args()

MWCC_VERSION = "2.0/sp1p5"   # Any 2.0 release matches so far; narrow down as more code is matched.
DECOMP_ME_COMPILER = "mwcc_30_131"
CC_FLAGS = " ".join([
    "-O4,p",            # Optimize maximally for performance
    "-proc arm946e",    # Target processor
    "-thumb",           # Most game code is Thumb; use `#pragma thumb off` for ARM functions
    "-interworking",    # ARM/Thumb interworking
    "-fp soft",         # Software floating point
    "-enum int",        # int-sized enums
    "-char signed",     # char is signed (ldrsb loads in the original code)
    "-lang c",          # Game uses C++ in places (.exceptix present); C until a C++ file is matched
    "-w off",
    "-sym on",
    "-nolink",
    "-msgstyle gcc",
])
# Extra flags for library code, by path prefix.
LIB_CC_FLAGS = {
    "libs/msl/": "-Cpp_exceptions off",   # MSL was built without exception tables
}
LD_FLAGS = " ".join([
    "-proc arm946e",
    "-dead",
    "-nostdlib",
    "-interworking",
    "-map closure,unused",
    "-msgstyle gcc",
    "-m Entry",
])

root = Path(".")
config_dir = root / "config" / args.version
arm9_config = config_dir / "arm9" / "config.yaml"
build_dir = root / "build" / args.version
extract_dir = root / "extract" / args.version
base_rom = root / "extract" / f"ff_{args.version}.nds"
built_rom = root / "build" / f"ff_{args.version}.nds"

system = platform.system()
exe = ".exe" if system == "Windows" else ""
wine = "" if system == "Windows" else (args.wine or "tools/bin/wibo")
DSD = f"tools/bin/dsd{exe}"
OBJDIFF = f"tools/bin/objdiff-cli{exe}"
CC = f"tools/mwccarm/{MWCC_VERSION}/mwccarm.exe"
LD = f"tools/mwccarm/{MWCC_VERSION}/mwldarm.exe"
PY = sys.executable

if not Path(DSD).exists():
    sys.exit("Build tools missing. Run: python3 tools/download_tools.py")
if not arm9_config.exists():
    sys.exit(f"Unknown version '{args.version}' (no {arm9_config})")


def dsd_json() -> dict:
    out = subprocess.check_output([DSD, "json", "delinks", "--config-path", str(arm9_config)])
    return json.loads(out)


lines: list[str] = []
w = lines.append

w("# Generated by tools/configure.py; edits are overwritten.")
w(f"rule configure\n  command = {PY} tools/configure.py {args.version}\n  generator = 1")
w(f"rule extract\n  command = {DSD} rom extract --rom $in --output-path {extract_dir}")
w(f"rule delink\n  command = {DSD} delink --config-path {arm9_config}")
w(f"rule lcf\n  command = {DSD} lcf -c {arm9_config}")
# mwcc names outputs after the source and writes a Windows-style .d next to them.
w(f"rule cc\n  command = {wine} {CC} {CC_FLAGS} $extra_cflags -gccinc -i include -i libs/msl/include -MD -c $in -o $outdir && {PY} tools/fix_dep.py $outdir/$stem.d $out.d\n"
  "  depfile = $out.d\n  deps = gcc\n  description = CC $in")
w(f"rule ld\n  command = {wine} {LD} {LD_FLAGS} @$objects $lcf -o $out\n  description = LINK $out")
w(f"rule check\n  command = {DSD} check modules --config-path {arm9_config} --fail && touch $out")
w(f"rule rom_config\n  command = {DSD} rom config --elf $in --config {arm9_config}")
w(f"rule rom_build\n  command = {DSD} rom build --config $in --rom $out && {PY} tools/fix_rom.py {base_rom} $out")
w(f"rule sha1\n  command = shasum -c config/{args.version}/ff_{args.version}.sha1 && touch $out")
w(f"rule objdiff_config\n  command = {DSD} objdiff --config-path {arm9_config} --output-path . --scratch "
  f"--compiler {DECOMP_ME_COMPILER} --c-flags \"{CC_FLAGS}\" --custom-make ninja")
w("")

dsd_configs = sorted(str(p) for p in config_dir.rglob("*.txt")) + [str(arm9_config)]
rom_config = extract_dir / "config.yaml"
w(f"build build.ninja: configure | tools/configure.py {' '.join(p for p in dsd_configs if p.endswith('delinks.txt'))}")
w(f"build {rom_config}: extract {base_rom}")

info = dsd_json()
delinked = [f["delink_file"] for f in info["files"]]
w(f"build {' '.join(delinked)}: delink {' '.join(dsd_configs)} {rom_config}")
lcf, objects = info["arm9_lcf_file"], info["arm9_objects_file"]
w(f"build {lcf} {objects}: lcf {' '.join(dsd_configs)} {rom_config}")

to_link = []
for f in info["files"]:
    obj = f["object_to_link"]
    to_link.append(obj)
    if obj != f["delink_file"]:   # a matched source file: compile it
        extra = next((v for k, v in LIB_CC_FLAGS.items() if f["name"].startswith(k)), "")
        w(f"build {obj}: cc {f['name']}\n  outdir = {Path(obj).parent}\n  stem = {Path(obj).stem}\n  extra_cflags = {extra}")

elf = build_dir / "arm9.o"
w(f"build {elf}: ld {' '.join(to_link)} | {lcf} {objects}\n  objects = {objects}\n  lcf = {lcf}")
w(f"build {build_dir}/check.ok: check {elf}")
rom_cfg = build_dir / "build" / "rom_config.yaml"
w(f"build {rom_cfg}: rom_config {elf} | {build_dir}/check.ok")
w(f"build {built_rom}: rom_build {rom_cfg}")
w(f"build {build_dir}/sha1.ok: sha1 {built_rom}")
w("build objdiff.json: objdiff_config " + " ".join(dsd_configs))
w(f"build check: phony {build_dir}/check.ok")
w(f"build rom: phony {build_dir}/sha1.ok")
w("default rom")

Path("build.ninja").write_text("\n".join(lines) + "\n")
print(f"Wrote build.ninja for '{args.version}'. Run: ninja")
